/**
 * Calculate Levenshtein distance between two strings
 */
export function levenshteinDistance(str1: string, str2: string): number {
  const m = str1.length;
  const n = str2.length;
  const dp: number[][] = Array(m + 1)
    .fill(null)
    .map(() => Array(n + 1).fill(0));

  for (let i = 0; i <= m; i++) dp[i][0] = i;
  for (let j = 0; j <= n; j++) dp[0][j] = j;

  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      if (str1[i - 1] === str2[j - 1]) {
        dp[i][j] = dp[i - 1][j - 1];
      } else {
        dp[i][j] = Math.min(dp[i - 1][j], dp[i][j - 1], dp[i - 1][j - 1]) + 1;
      }
    }
  }

  return dp[m][n];
}

/**
 * Calculate similarity score between two strings (0 to 1)
 */
export function calculateSimilarity(str1: string, str2: string): number {
  if (str1 === str2) return 1.0;

  const s1 = str1.toLowerCase();
  const s2 = str2.toLowerCase();

  if (s1 === s2) return 0.95;

  const maxLen = Math.max(s1.length, s2.length);
  const distance = levenshteinDistance(s1, s2);

  return 1 - distance / maxLen;
}

/**
 * Normalize column name by removing common prefixes/suffixes
 */
export function normalizeColumnName(name: string): string {
  let normalized = name.toLowerCase().trim();

  // Remove common prefixes
  for (const prefix of COLUMN_MATCHING.commonPrefixes) {
    if (normalized.startsWith(prefix)) {
      normalized = normalized.substring(prefix.length);
      break;
    }
  }

  // Remove common suffixes
  for (const suffix of COLUMN_MATCHING.commonSuffixes) {
    if (normalized.endsWith(suffix)) {
      normalized = normalized.substring(0, normalized.length - suffix.length);
      break;
    }
  }

  return normalized;
}

// ============================================================================
// Column Matching Functions
// ============================================================================

/**
 * Find best matching column from a list of target columns
 */
export function findBestMatch(
  sourceColumn: string,
  targetColumns: string[]
): { column: string; confidence: number } | null {
  if (targetColumns.length === 0) return null;

  let bestMatch = targetColumns[0];
  let bestScore = 0;

  const normalizedSource = normalizeColumnName(sourceColumn);

  for (const targetColumn of targetColumns) {
    // Check for exact match first
    if (sourceColumn === targetColumn) {
      return { column: targetColumn, confidence: COLUMN_MATCHING.exactMatchScore };
    }

    // Check for case-insensitive match
    if (sourceColumn.toLowerCase() === targetColumn.toLowerCase()) {
      bestMatch = targetColumn;
      bestScore = 0.95;
      continue;
    }

    // Check normalized match
    const normalizedTarget = normalizeColumnName(targetColumn);
    if (normalizedSource === normalizedTarget) {
      if (0.9 > bestScore) {
        bestMatch = targetColumn;
        bestScore = 0.9;
      }
      continue;
    }

    // Calculate similarity score
    const similarity = calculateSimilarity(sourceColumn, targetColumn);
    if (similarity > bestScore) {
      bestMatch = targetColumn;
      bestScore = similarity;
    }

    // Also check normalized similarity
    const normalizedSimilarity = calculateSimilarity(normalizedSource, normalizedTarget);
    if (normalizedSimilarity > bestScore) {
      bestMatch = targetColumn;
      bestScore = normalizedSimilarity * 0.85; // Slight penalty for normalization
    }
  }

  // Only return if above threshold
  if (bestScore >= COLUMN_MATCHING.similarityThreshold) {
    return { column: bestMatch, confidence: bestScore };
  }

  return null;
}

/**
 * Generate field mappings between source and target columns
 */
export function generateFieldMappings(
  sourceColumns: string[],
  targetColumns: string[]
): MappingRule[] {
  const mappings: MappingRule[] = [];
  const usedTargetColumns = new Set<string>();

  for (const sourceColumn of sourceColumns) {
    // Filter out already used target columns
    const availableTargets = targetColumns.filter(col => !usedTargetColumns.has(col));

    const match = findBestMatch(sourceColumn, availableTargets);

    if (match) {
      mappings.push({
        sourceColumn,
        targetColumn: match.column,
        transformationType: 'direct',
        isAutogenerated: true,
      });
      usedTargetColumns.add(match.column);
    }
  }

  return mappings;
}

