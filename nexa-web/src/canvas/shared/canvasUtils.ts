/**
 * Calculate position for a node in a column
 */
export function calculateNodePosition(
  nodeIndex: number,
  totalNodes: number,
  columnX: number,
  config: LayoutConfig
): LayoutPosition {
  const totalHeight = totalNodes * (config.nodeHeight + config.verticalSpacing);
  const startY = -totalHeight / 2;
  const y = startY + nodeIndex * (config.nodeHeight + config.verticalSpacing);

  return { x: columnX, y };
}

/**
 * Calculate positions for nodes in a column
 */
export function layoutNodesInColumn(
  nodes: CanvasNode[],
  columnX: number,
  config: LayoutConfig
): CanvasNode[] {
  return nodes.map((node, index) => {
    const position = calculateNodePosition(index, nodes.length, columnX, config);
    return {
      ...node,
      position,
    };
  });
}

/**
 * Center nodes vertically in the canvas
 */
export function centerNodesVertically(nodes: CanvasNode[]): CanvasNode[] {
  if (nodes.length === 0) return nodes;

  const yPositions = nodes.map(n => n.position.y);
  const minY = Math.min(...yPositions);
  const maxY = Math.max(...yPositions);
  const centerOffset = -(minY + maxY) / 2;

  return nodes.map(node => ({
    ...node,
    position: {
      x: node.position.x,
      y: node.position.y + centerOffset,
    },
  }));
}

