/**
 * Infer data type from column name and sample data
 */
export function inferDataType(columnName: string, sampleData?: any): string {
  const name = columnName.toLowerCase();

  // Check column name patterns
  if (name.includes('id') || name.endsWith('_id')) return 'integer';
  if (name.includes('email') || name.includes('mail')) return 'string';
  if (name.includes('phone') || name.includes('mobile')) return 'string';
  if (name.includes('date') && !name.includes('update')) return 'date';
  if (name.includes('timestamp') || name.includes('created') || name.includes('updated')) return 'timestamp';
  if (name.includes('amount') || name.includes('price') || name.includes('cost')) return 'float';
  if (name.includes('count') || name.includes('quantity')) return 'integer';
  if (name.includes('flag') || name.includes('is_') || name.includes('has_')) return 'boolean';
  if (name.includes('json') || name.includes('metadata')) return 'json';
  if (name.includes('tags') || name.includes('categories')) return 'array';

  // Check sample data if available
  if (sampleData !== undefined && sampleData !== null) {
    const type = typeof sampleData;
    if (type === 'number') {
      return Number.isInteger(sampleData) ? 'integer' : 'float';
    }
    if (type === 'boolean') return 'boolean';
    if (Array.isArray(sampleData)) return 'array';
    if (type === 'object') return 'json';
  }

  // Default to string
  return 'string';
}

/**
 * Get display name for data type
 */
export function getDataTypeDisplay(dataType: string): string {
  const typeMap: Record<string, string> = {
    string: 'String',
    integer: 'Integer',
    float: 'Float',
    boolean: 'Boolean',
    date: 'Date',
    timestamp: 'Timestamp',
    json: 'JSON',
    array: 'Array',
  };

  return typeMap[dataType] || 'Unknown';
}
