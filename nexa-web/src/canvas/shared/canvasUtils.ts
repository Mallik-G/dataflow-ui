/**
 * Generate a curved Bezier path for an edge
 */
export function generateCurvedPath(
  sourceX: number,
  sourceY: number,
  targetX: number,
  targetY: number
): string {
  const offset = Math.abs(targetX - sourceX) * 0.3;
  const controlPoint1X = sourceX + offset;
  const controlPoint1Y = sourceY;
  const controlPoint2X = targetX - offset;
  const controlPoint2Y = targetY;

  return `M ${sourceX} ${sourceY} C ${controlPoint1X} ${controlPoint1Y} ${controlPoint2X} ${controlPoint2Y} ${targetX} ${targetY}`;
}

/**
 * Generate a stepped path for an edge
 */
export function generateSteppedPath(
  sourceX: number,
  sourceY: number,
  targetX: number,
  targetY: number
): string {
  const midX = (sourceX + targetX) / 2;

  return `M ${sourceX} ${sourceY} L ${midX} ${sourceY} L ${midX} ${targetY} L ${targetX} ${targetY}`;
}

// ============================================================================
// Node Filtering Functions
// ============================================================================

/**
 * Filter nodes by entity type
 */
export function filterNodesByType(nodes: CanvasNode[], entityType: string): CanvasNode[] {
  return nodes.filter(node => {
    const data = node.data as any;
    switch (entityType) {
      case 'raw':
        return data.isRawFile === true;
      case 'curated':
        return data.isCuratedFile === true;
      case 'consumption':
        return data.isConsumptionFile === true;
      default:
        return false;
    }
  });
}

/**
 * Filter edges connected to a specific node
 */
export function getConnectedEdges(nodeId: string, edges: CanvasEdge[]): CanvasEdge[] {
  return edges.filter(edge => edge.source === nodeId || edge.target === nodeId);
}

/**
 * Get all source nodes for a target node
 */
export function getSourceNodes(targetNodeId: string, nodes: CanvasNode[], edges: CanvasEdge[]): CanvasNode[] {
  const sourceIds = edges
    .filter(edge => edge.target === targetNodeId)
    .map(edge => edge.source);

  return nodes.filter(node => sourceIds.includes(node.id));
}

/**
 * Get all target nodes for a source node
 */
export function getTargetNodes(sourceNodeId: string, nodes: CanvasNode[], edges: CanvasEdge[]): CanvasNode[] {
  const targetIds = edges
    .filter(edge => edge.source === sourceNodeId)
    .map(edge => edge.target);

  return nodes.filter(node => targetIds.includes(node.id));
}

